const I18nContext = createContext<I18nContextType | null>(null);

function fallbackLabel(key: string) {
  const leaf = key.split(".").pop() || key;
  const human = leaf
    .replace(/[_-]+/g, " ")
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .trim();
  return human ? human.charAt(0).toUpperCase() + human.slice(1) : key;
}

export function translateForLocale(
  locale: Locale,
  key: string,
  replacements?: Record<string, string>,
): string {
  let str = translations[locale][key] || translations.en[key] || fallbackLabel(key);
  if (replacements) {
    Object.entries(replacements).forEach(([k, v]) => {
      str = str.replaceAll(`{${k}}`, v);
    });
  }
  return str;
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    const saved = localStorage.getItem("novamail-locale");
    return isLocale(saved) ? saved : "en";
  });

  const setLocale = (newLocale: Locale) => {
    setLocaleState(newLocale);
    localStorage.setItem("novamail-locale", newLocale);
  };

  useEffect(() => {
    document.documentElement.dir = isRtlLocale(locale) ? "rtl" : "ltr";
    document.documentElement.lang = getIntlLocale(locale);
  }, [locale]);

  const t = (key: string, replacements?: Record<string, string>) =>
    translateForLocale(locale, key, replacements);

  return (
    <I18nContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
